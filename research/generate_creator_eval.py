OUT = Path(__file__).resolve().parent / "data" / "creator_eval.csv"
MIN_DISTINCT = 150


def main() -> None:
    texts = [t for t, _ in DISTINCT_COMMENTS]
    if len(texts) != len(set(texts)):
        raise ValueError("Duplicate comment texts in DISTINCT_COMMENTS")
    if len(texts) < MIN_DISTINCT:
        raise ValueError(f"Need at least {MIN_DISTINCT} distinct comments, got {len(texts)}")

    rows = [
        {
            "id": str(i + 1),
            "text": text,
            "label_expected": label,
            "synthetic": "yes",
            "manual_correction": "",
        }
        for i, (text, label) in enumerate(DISTINCT_COMMENTS)
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(
            f, fieldnames=["id", "text", "label_expected", "synthetic", "manual_correction"]
        )
        w.writeheader()
        w.writerows(rows)
    print(f"Wrote {len(rows)} distinct comments to {OUT}")


if __name__ == "__main__":
    main()